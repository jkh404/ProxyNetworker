  function translatePhrase(value, language) {
    const text = String(value || '');
    const trimmed = text.trim();
    if (!trimmed) return text;
    const dictionary = language === 'en-US' ? chineseToEnglish : englishToChinese;
    let translated = language === 'zh-CN'
      ? (dictionary[trimmed] || chineseAliases[trimmed] || trimmed)
      : (englishAliases[trimmed] || dictionary[trimmed] || trimmed);
    for (const [pattern, replacement] of patterns[language] || []) {
      if (pattern.test(translated)) {
        translated = translated.replace(pattern, replacement);
        break;
      }
    }
    const leading = text.match(/^\s*/)?.[0] || '';
    const trailing = text.match(/\s*$/)?.[0] || '';
    return `${leading}${translated}${trailing}`;
  }

  function shouldSkip(node) {
    let element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    while (element) {
      if (element.matches?.('script, style, code, pre, textarea, [data-i18n-ignore]')) return true;
      element = element.parentElement;
    }
    return false;
  }

  function translateDocument(root, language) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (shouldSkip(node)) continue;
      const next = translatePhrase(node.nodeValue, language);
      if (next !== node.nodeValue) node.nodeValue = next;
    }
    for (const element of root.querySelectorAll?.('[placeholder], [aria-label], [title], [data-label]') || []) {
      if (shouldSkip(element)) continue;
      for (const attribute of ['placeholder', 'aria-label', 'title', 'data-label']) {
        const value = element.getAttribute(attribute);
        if (!value) continue;
        const next = translatePhrase(value, language);
        if (next !== value) element.setAttribute(attribute, next);
      }
    }
  }

  window.ProxyNetworkerI18n = { translatePhrase, translateDocument };
